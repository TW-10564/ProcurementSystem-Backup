class Recorder:
    """Thin wrapper that keeps cursor, caption and timing in one place."""

    def __init__(self, page, captions):
        self.page = page
        self.captions = captions
        self.i = 0
        self.started = time.time()

    def ensure_overlay(self):
        self.page.evaluate(CURSOR_JS)

    def say(self, seconds: float, index: int | None = None):
        """Show the next caption (or a specific one) and hold it."""
        idx = self.i if index is None else index
        text = self.captions[idx]
        self.i = idx + 1
        self.ensure_overlay()
        self.page.evaluate("(t) => window.__demoSay(t)", text)
        self.page.wait_for_timeout(int(seconds * 1000 * SPEED))

    def shot(self, name: str):
        SHOT_DIR.mkdir(parents=True, exist_ok=True)
        self.page.screenshot(path=str(SHOT_DIR / f"{name}.png"))

    def clear_caption(self):
        self.page.evaluate("() => window.__demoSay('')")

    def glide(self, x: float, y: float, steps: int = 22):
        """Move the visible dot AND the real mouse together.

        Both, not just the dot: hover styles and dropdowns react to the real
        pointer, and a video where the highlight does not follow the cursor
        looks broken.
        """
        self.ensure_overlay()
        self.page.mouse.move(x, y, steps=steps)
        self.page.evaluate("([x,y]) => window.__demoMove(x,y)", [x, y])
        self.page.wait_for_timeout(120)

    def click_at(self, locator, settle: int = 900):
        box = locator.bounding_box()
        if box is None:
            raise RuntimeError("target not visible")
        x = box["x"] + box["width"] / 2
        y = box["y"] + box["height"] / 2
        self.glide(x, y)
        self.page.evaluate("() => window.__demoClick()")
        self.page.wait_for_timeout(180)
        locator.click()
        self.page.wait_for_timeout(int(settle * SPEED))
        self.ensure_overlay()

    def nav(self, path: str, settle: int = 1400):
        """Navigate and wait for the page to actually have its DATA.

        A fixed pause is not enough: the heavier pages fetch several reports
        after first paint, and the first take filmed the forecast screen with
        every tile still showing a dash and "読み込み中…" under it. Waiting for
        the network to go quiet films the finished screen; the timeout keeps a
        slow endpoint from stalling the whole recording.
        """
        self.page.goto(f"{DEMO_BASE}{path}")
        try:
            self.page.wait_for_load_state("networkidle", timeout=12000)
        except Exception:
            pass
        self.page.wait_for_timeout(int(settle * SPEED))
        self.ensure_overlay()

    def scroll(self, amount: int = 420, settle: int = 700):
        self.page.mouse.wheel(0, amount)
        self.page.wait_for_timeout(int(settle * SPEED))

    def elapsed(self) -> float:
        return time.time() - self.started


def record(lang: str, headless: bool = True) -> Path:
    captions = SCRIPTS[lang]
    tmp_dir = Path("/tmp/onefcst-demo-record")
    shutil.rmtree(tmp_dir, ignore_errors=True)
    tmp_dir.mkdir(parents=True, exist_ok=True)

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=headless)
        context = browser.new_context(
            viewport=VIEWPORT,
            record_video_dir=str(tmp_dir),
            record_video_size=VIEWPORT,
            locale="ja-JP" if lang == "ja" else "en-US",
        )
        # The UI language is a localStorage preference, not a browser locale,
        # so a ja-JP context alone still rendered the English UI in the first
        # take — Japanese captions over English screens. Set it before any
        # script runs, on every page in the context.
        context.add_init_script(
            f"try {{ localStorage.setItem('onefcst_lang', '{lang}'); }} catch (e) {{}}")
        page = context.new_page()
        r = Recorder(page, captions)

        # ---- scene 1: title + the landing page (~14s) --------------------
        r.nav("/", settle=1800)
        r.say(5)                                   # title card
        r.say(5)                                   # sign-in explanation

        enter = page.get_by_role("button").first
        try:
            r.click_at(enter, settle=1200)
        except Exception:
            r.nav("/app")

        # The Microsoft credential screen is deliberately not filmed — see the
        # module docstring. We caption what happens there instead.
        r.say(4)

        # ---- scene 2: dashboard (~18s) ------------------------------------
        r.nav("/app", settle=1800)
        r.say(7)
        r.scroll(400)
        r.shot("dashboard")
        r.page.wait_for_timeout(1200)
        r.scroll(-400, settle=500)

        # ---- scene 3: forecast list + detail (~30s) -----------------------
        r.nav("/app/forecast", settle=2000)
        r.shot("forecast")
        r.say(8)
        r.scroll(300)
        rows = page.locator("table tbody tr")
        try:
            if rows.count() > 0:
                r.click_at(rows.first, settle=2000)
        except Exception:
            pass
        r.say(9)
        r.scroll(420)
        page.wait_for_timeout(900)

        # ---- scene 4: order suggestions (~22s) ----------------------------
        r.nav("/app/forecast?tab=orders", settle=1600)
        orders = page.get_by_text("発注" if lang == "ja" else "Order").first
        try:
            r.click_at(orders, settle=1500)
        except Exception:
            pass
        r.say(8)
        r.scroll(380)
        r.say(6)                                   # the PO caveat

        # ---- scene 5: adjustments, the core write flow (~34s) -------------
        r.nav("/app/adjustments", settle=1800)
        r.shot("adjustments")
        r.say(7)
        r.say(5)                                   # author is fixed
        try:
            search = page.locator("input").first
            r.click_at(search, settle=400)
            search.type("CPU", delay=110)
            page.wait_for_timeout(1400)
            option = page.locator("div").filter(has_text="(CPU)").last
            r.click_at(option, settle=800)
        except Exception:
            pass
        r.say(8)
        r.scroll(320)

        # ---- scene 6: compatibility review (~18s) -------------------------
        r.nav("/app/compat", settle=2000)
        r.shot("compat")
        r.say(8)
        r.scroll(400)
        page.wait_for_timeout(800)

        # ---- scene 7: mismatch (~14s) -------------------------------------
        r.nav("/app/mismatch", settle=1800)
        r.shot("mismatch")
        r.say(7)
        r.scroll(350)

        # ---- scene 8: accuracy / FVA (~14s) -------------------------------
        r.nav("/app/accuracy", settle=1800)
        r.shot("accuracy")
        r.say(7)
        r.scroll(350)

        # ---- scene 9: audit log (~14s) ------------------------------------
        r.nav("/app/notifications", settle=1800)
        r.shot("audit")
        r.say(7)
        r.scroll(320)

        # ---- scene 10: profile + close (~16s) -----------------------------
        r.nav("/app/profile", settle=1600)
        r.shot("profile")
        r.say(6)
        r.nav("/app", settle=1200)
        r.say(6)
        r.clear_caption()
        page.wait_for_timeout(600)

        elapsed = r.elapsed()
        video = page.video
        context.close()
        browser.close()

        src = Path(video.path())
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        dest = OUT_DIR / f"demo-{lang}.webm"
        shutil.move(str(src), dest)

    size_mb = dest.stat().st_size / 1_000_000
    print(f"[{lang}] {dest}  {size_mb:.1f} MB  ~{elapsed:.0f}s "
          f"(target {TARGET_SECONDS}s)")
    if elapsed > 190:
        print(f"[{lang}] WARNING: over three minutes — shorten a scene.")
    return dest


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--lang", choices=("ja", "en", "both"), default="both")
    ap.add_argument("--headed", action="store_true",
                    help="watch it record (useful when a selector breaks)")
    args = ap.parse_args()

    langs = ("ja", "en") if args.lang == "both" else (args.lang,)
    for lang in langs:
        record(lang, headless=not args.headed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
